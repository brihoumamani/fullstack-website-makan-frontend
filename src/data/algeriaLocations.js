// Helper to get communes for a given wilaya
export const getCommunesByWilaya = (wilayaNameOrCode) => {
  if (!wilayaNameOrCode) return [];
  const wilaya = ALGERIA_WILAYAS.find(
    (w) =>
      w.name.toLowerCase() === wilayaNameOrCode.toLowerCase() ||
      w.code === wilayaNameOrCode ||
      w.nameAr === wilayaNameOrCode
  );
  return wilaya ? wilaya.communes : [];
};
